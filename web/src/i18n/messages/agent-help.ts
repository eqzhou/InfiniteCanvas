export type AgentHelpMessageKey = keyof typeof agentHelpZhCN;

export type AgentHelpTranslator = (
  key: AgentHelpMessageKey,
  params?: Readonly<Record<string, string | number>>,
) => string;

export function createAgentHelpTranslator(
  baseT: (key: never, params?: Readonly<Record<string, string | number>>) => string,
  locale: "zh-CN" | "en-US",
): AgentHelpTranslator {
  return (key, params) => {
    try {
      return baseT(key as never, params);
    } catch {
      let value = locale === "en-US" ? agentHelpEnUS[key] : agentHelpZhCN[key];
      for (const [name, replacement] of Object.entries(params ?? {})) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
      return value;
    }
  };
}
